package uz.salvadore.hamkorbank.archi.advisor.domain.common;

/**
 * Класс отказа помощника. Не HTTP-код, а смысл, из которого адаптер выводит код.
 * У помощника классов больше, чем у modeling: лимиты расхода — его собственная
 * причина отказа, а внешний API — его собственная зависимость.
 */
public enum Failure {
    /** Объекта нет — или он скрыт списком доступа. */
    NOT_FOUND,
    /** Тот же ключ идемпотентности с другими параметрами или сессия с ним ещё идёт. */
    CONFLICT,
    /** Запрос сам по себе недопустим. */
    UNPROCESSABLE,
    /** Роль не даёт права на операцию или помощник выключен. */
    FORBIDDEN,
    /** Месячный бюджет исчерпан или превышена частота обращений. */
    TOO_MANY_REQUESTS,
    /** Контекст не помещается даже усечённым. */
    TOO_LARGE,
    /** Внешний API не ответил. */
    UNAVAILABLE
}

package uz.salvadore.hamkorbank.archi.modeling.domain.common;

/**
 * Класс отказа домена. Не HTTP-код, а смысл, из которого адаптер выводит код:
 * домен не знает про HTTP, но знает, чем «нет такого» отличается от «нельзя сейчас».
 */
public enum Failure {
    /** Объекта нет — или он скрыт списком доступа. */
    NOT_FOUND,
    /** Нельзя в текущем состоянии: чужая блокировка, удалённая модель, связи у элемента. */
    CONFLICT,
    /** Запрос сам по себе недопустим: имя длиннее предела, папка чужой модели, тип не той фазы. */
    UNPROCESSABLE,
    /** Роль или список доступа не дают права на операцию. */
    FORBIDDEN,
    /** Было, но больше нет и не будет: снимок версии очищен, а Git не настроен. */
    GONE
}

package uz.salvadore.hamkorbank.archi.interchange.domain.git;

/** Состояние привязки: от него зависит, публикуются ли версии и чистятся ли снимки. */
public enum GitBindingStatus {
    /** Репозиторий отвечал при последнем обращении. */
    CONFIGURED,
    /** Не отвечает или отказывает в доступе: публикация ждёт, очистка снимков стоит. */
    UNREACHABLE,
    /** Снята администратором. Терминально: новая настройка — новая привязка. */
    DISABLED
}

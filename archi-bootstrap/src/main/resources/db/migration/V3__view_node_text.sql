-- ───────────────────────────────────────────────────────────────────
-- V3 — собственный текст узла представления в столбцах, а не в остатке XML.
--
--   * label   — атрибут name узла: подпись группы, объектов скетча и холста.
--               У узла над элементом подписью служит имя элемента, своей нет.
--   * content — текст заметки из дочернего <content> как есть, с переводами строк.
--
-- Пусто — у узла этого текста нет (атрибута или <content> в файле нет); пустая
-- строка — есть, но пустой. Узлы, импортированные до этой миграции, держат текст
-- в остатке буквально: выгрузка их не меняется, а столбцы заполнит повторный импорт.
-- ───────────────────────────────────────────────────────────────────

ALTER TABLE view_node
    ADD COLUMN label   text,
    ADD COLUMN content text;
